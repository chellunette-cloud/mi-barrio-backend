CREATE TABLE IF NOT EXISTS barrio (
  id SERIAL PRIMARY KEY,
  slug TEXT NOT NULL UNIQUE,
  nombre TEXT NOT NULL,
  nombre_mostrar TEXT NOT NULL,
  codigo_id TEXT,
  localidad_codigo TEXT NOT NULL,
  localidad_nombre TEXT NOT NULL,
  upz_codigo TEXT NOT NULL,
  upz_nombre TEXT NOT NULL,
  upl TEXT NOT NULL,
  area_ha NUMERIC(10, 2) NOT NULL,
  area_m2 NUMERIC(14, 2),
  lotes INTEGER NOT NULL,
  poblacion_estimada INTEGER NOT NULL,
  poblacion_tipo TEXT NOT NULL DEFAULT 'estimacion_registro_barrio',
  densidad NUMERIC(12, 4),
  estrato_predominante INTEGER,
  manzanas_estrato2 INTEGER NOT NULL DEFAULT 0,
  centroide GEOMETRY(Point, 4326) NOT NULL,
  geom GEOMETRY(Polygon, 4326) NOT NULL,
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT barrio_geom_srid CHECK (ST_SRID(geom) = 4326),
  CONSTRAINT barrio_centroide_srid CHECK (ST_SRID(centroide) = 4326)
);
